function buildUserDetails(users: any[]) {
  const map: Record<string, any> = {}
  for (const u of users || []) {
    map[u.upn] = {
      displayName: u.displayName ?? u.name,
      upn: u.userPrincipalName ?? u.upn,
      userType: u.userType ?? 'Member',
      accountEnabled: u.accountEnabled ?? true,
      status: u.status ?? 'Active',
      department: u.department ?? '',
      jobTitle: u.jobTitle ?? '',
      location: u.location ?? '',
      risk: u.risk ?? 'low',
      mfa: !!(u.mfaEnabled ?? u.mfa),
      authMethods: Array.isArray(u.authMethods) ? u.authMethods : [],
      roles: Array.isArray(u.roles) ? u.roles : [],
      groups: Array.isArray(u.groups) ? u.groups : [],
      devices: Array.isArray(u.devices) ? u.devices : [],
      lastSignIn: u.lastSignIn ?? '',
      created: u.created ?? '',
    }
  }
  return map
}

